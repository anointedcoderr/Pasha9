// Built by Anointed Coder.
//
// Pasha WinGo round engine: the money core. Mirrors the existing native
// games (dice / mines / crash) for every wallet movement, ledger write,
// turnover accrual and cashback scope stamping. Nothing here trusts the
// client: round state, bet acceptance, the draw and every payout are
// decided server-side.
//
// The pieces:
//   - computeRoundWindow(mode, at)  epoch-anchored deterministic window
//   - ensureRounds(mode)            idempotent upsert of current + next
//   - computeResult(seed, period)   crypto 0..9 from the committed seed
//   - placeBet(input)               guarded wallet debit + WingoBet
//   - settleRound(roundId)          guarded draw + exactly-once payout
//   - wingoTick()                   cron driver: ensure + close + settle
//
// Money safety guarantees (the whole point):
//   1. A bet at/after betCloseAt is rejected server-side, not just hidden.
//   2. The draw is generated by exactly one caller: status open|closed ->
//      drawn via a guarded updateMany so concurrent crons cannot re-roll.
//   3. Each bet is paid exactly once: the WON/LOST flip is a guarded
//      updateMany on status = PENDING, so a re-run or a concurrent tick
//      can never double-pay or double-debit.
//   4. Re-running settlement on an already-settled round is a no-op.
//   5. Winnings are credited through the same wallet + Transaction ledger
//      path (type 'win', meta.scope 'casino') the other native games use,
//      so turnover and cashback scope accrue identically.

